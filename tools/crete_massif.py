"""Measure the highest silhouette the massif reaches over one full turn, and freeze it.

For every column of the 3840 x 944 source frame, take the topmost row where
alpha > 8 across ALL the images of the sequence (180 frames, one full looping
turn: `massif.py --tour --images 180`, the last frame joins the first). Columns
are then grouped in bins of 64 and each bin keeps its MINIMUM row: y grows
downward, so the minimum is the highest point, the conservative choice. A bin
with no massif at all (frame edges) is written as the frame height, 944.

The result is written to src/scene/crete.ts.

THE SOURCE SEQUENCE LIVES OUTSIDE THE REPOSITORY (~/projet_zero/montagne_hd/
tramage/webp/). This script can only be replayed on a machine that has those
files; src/scene/crete.ts is a first-class committed source, not a build output.

Usage:
  python3 -I tools/crete_massif.py
"""
from datetime import date
from pathlib import Path

import numpy as np
from PIL import Image

SRC = Path.home() / "projet_zero" / "montagne_hd" / "tramage" / "webp"
OUT = Path(__file__).resolve().parent.parent / "src" / "scene" / "crete.ts"
BIN = 64
ALPHA_MIN = 8

# Safety margin kept above the crest, in SCREEN pixels. It is the hover radius
# of a star (RAYON_SURVOL in src/scene/StarLayer.ts, 14 px), which already
# covers the 9 px halo. Because the true per-column maximum is stored rather
# than a smoothed curve, the smoothing error disappears; what remains is the gap
# between the GLSL port and the reference render, and the 2 degree sampling of
# the turn, both small.
MARGE_CRETE = 14


def main() -> None:
    files = sorted(SRC.glob("*.webp"))
    if not files:
        raise SystemExit(f"no .webp found in {SRC}")
    top = None
    for f in files:
        with Image.open(f) as im:
            a = np.asarray(im.convert("RGBA"))[:, :, 3]
        mask = a > ALPHA_MIN
        h = mask.shape[0]
        first = np.where(mask.any(axis=0), mask.argmax(axis=0), h)
        top = first if top is None else np.minimum(top, first)
    width = top.shape[1] if top.ndim > 1 else top.shape[0]
    assert width % BIN == 0, width
    crete = top.reshape(-1, BIN).min(axis=1)
    values = ", ".join(str(int(v)) for v in crete)
    OUT.write_text(
        f"""// Generated by tools/crete_massif.py on {date.today().isoformat()}
// Command: python3 -I tools/crete_massif.py
//
// Highest silhouette of the massif over one full turn ({len(files)} frames),
// as the topmost row where alpha > {ALPHA_MIN}, per bin of {BIN} source columns
// (minimum of the bin: the conservative choice, y grows downward).
// Rows are in the 3840 x 944 source frame. 944 means "no massif in this bin".
//
// THE SOURCE SEQUENCE LIVES OUTSIDE THIS REPOSITORY (~/projet_zero/montagne_hd/
// tramage/webp/): the script can only be replayed on a machine that has it.
// This file is therefore a first-class committed source.

export const CRETE_BIN = {BIN}

export const CRETE: readonly number[] = [
  {values},
]

// Safety margin above the crest, in SCREEN pixels: the hover radius of a star
// (RAYON_SURVOL in StarLayer.ts), which already covers its 9 px halo. The true
// per-column maximum is stored, not a smoothing, so smoothing error vanishes;
// what remains is the gap between the GLSL port and the reference render, and
// the 2 degree sampling of the turn, both small.
export const MARGE_CRETE = {MARGE_CRETE}
"""
    )
    empty = int((crete >= 944).sum())
    print(f"wrote {OUT}: {len(crete)} values, top row {int(crete.min())}, {empty} empty bins")


if __name__ == "__main__":
    main()
